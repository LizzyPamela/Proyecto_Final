    private void EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarActionPerformed
        int fila = jTable1.getSelectedRow();
        int i = JOptionPane.showConfirmDialog(this,"¿Desea eliminar el registro con el alumno " + jTable1.getValueAt(fila,0) + "?" ,"Confirmar",JOptionPane.YES_NO_OPTION);
        if(i == 0)
        {
            try{
                String SQL = "DELETE FROM contact_list WHERE alumno=" + jTable1.getValueAt(fila,0);
                sent = con.createStatement();
                int n = sent.executeUpdate(SQL);
                if(n > 0){
                    llenartabla();
                    limpiarCajas();
                    deshabilitar();
                    reiniciarBotones();
                    JOptionPane.showMessageDialog(null,"El registro se ha eliminado correctamente");
                }
            }catch(Exception e){
                JOptionPane.showMessageDialog(null,"Ha ocurrido un error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_EliminarActionPerformed

