    private void ActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ActualizarActionPerformed
         try {
        String SQL = "UPDATE contact_list SET nombre=?, apellido=?, telefono=?, email=?" 
                + "WHERE alumno=?";
            int fila = jTable1.getSelectedRow();
            String dato = (String)jTable1.getValueAt(fila, 0);
            PreparedStatement pst = con.prepareStatement(SQL);
            pst.setString(1,nombre.getText());
            pst.setString(2,apellido.getText());
            pst.setString(3,telefono.getText());
            pst.setString(4,email.getText());
            pst.setString(5,dato);
            
            int n = pst.executeUpdate();
            if(n > 0){
                llenartabla();
                JOptionPane.showMessageDialog(null,"Datos guardados correctamente.");}
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,"Se ha producido un error: " + e); }
    }//GEN-LAST:event_ActualizarActionPerformed

